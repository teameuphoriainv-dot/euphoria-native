import type { PixelSprite } from "./types";

/**
 * The Euphoria sprite library.
 *
 * All 16x16, all drawn against the shared orchid palette (see palette.ts), all
 * original art. Characters: K/k ink, P/p/q/Q orchid, G/g/y gold, N/n/m green,
 * R/r/s red, w/W/x/X neutral, T/t teal, F/f pink, B/b blue, `.` transparent.
 *
 * 16x16 is the working size because it is the smallest grid that still carries a
 * readable silhouette, and because these render beside 16-24px UI text. Draw the
 * silhouette first: if the shape does not read as a black blob, no amount of
 * shading rescues it.
 */

const s = (
  id: string,
  name: string,
  tags: string[],
  blurb: string,
  rows: string[],
  anim?: { frameMs: number; frames: string[][] },
): PixelSprite => ({ id, name, tags, blurb, rows, ...anim });

/**
 * Derives a frame by swapping palette characters, for animations that are purely
 * a lighting change (a bolt flashing, a heart beating). Writing those frames out
 * by hand is how miscounted rows get in; a substitution cannot change the
 * geometry, so it cannot break the sprite.
 */
const shade = (rows: string[], swap: Record<string, string>): string[] =>
  rows.map((row) => [...row].map((ch) => swap[ch] ?? ch).join(""));

/**
 * Derives a frame by replacing specific rows, for animations where only part of
 * the sprite moves (a rocket's exhaust, a highlight sweeping a trophy). Keeps
 * the untouched rows literally shared, so the still and its frames cannot drift.
 */
const withRows = (rows: string[], overrides: Record<number, string>): string[] =>
  rows.map((row, i) => overrides[i] ?? row);

