/**
 * THE CAST. Twenty-six pixel characters a player can wear as their avatar.
 *
 * WHY THESE AND NOT SYMBOLS. The first picker offered catalogue marks: a whale, a rocket, a crown.
 * The owner's correction was exact and right: "actual characters, not just some random symbols".
 * A symbol labels you. A character IS you, and being somebody is what an avatar is for.
 *
 * THEN: MAKE THEM TUFF. The second note was that the cast had to have aura, the kind of thing a
 * teenager would actually want to wear. That is what the hair and the accessories are for. Afros,
 * mohawks, braids, dreads, durags, beanies, ponytails and buzzes, worn with shades, headphones and
 * a chain. A finance app for 13-year-olds that ships a cast of polo shirts has already lost them.
 *
 * GENERATED FROM PARTS, not drawn twenty-six times, so the set cannot drift: one head, one face,
 * fifteen hair styles, four skin tones with a shadow each, three worn accessories, and a shirt from
 * the shared palette. Light comes from the left on every one, the same direction as every other
 * figure in the app.
 *
 * ORDER MATTERS IN THE GENERATOR: accessories are drawn LAST, so a chain sits on the shirt and
 * shades sit over the eyes rather than under them.
 *
 * EACH CARRIES ITS OWN PALETTE. Skin and hair are not in the Euphoria palette and should not be:
 * they are not UI colours, and adding them would invite their use as one. Carrying them per-sprite
 * also means a character never retints under the light-mode canvas, which is correct.
 *
 * ONE CHARACTER PER PIXEL. The generator's first draft used two-letter keys like `s1`, which reads
 * better in source and produces rows of the wrong WIDTH. compile.ts rejected it immediately, which
 * is exactly what that validation is for.
 */
