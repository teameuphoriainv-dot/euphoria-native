/**
 * Business Strategy art kit, batch B (lessons 10 to 17): two more rooms, and what furnishes them.
 *
 * Sets (80x60 opener bases, like bsWarRoom): a tavern, plaster between dark timbers under a heavy
 * beam, and a round tower study with a bookcase and a tall arched window. The tavern's hearth and its
 * door are pieces rather than part of the base, so the room can face a different way in each lesson
 * (the fire burns on the right in one, on the left in another). The cast adds a townsperson seen from
 * behind, for a crowd that looks at something in the scene instead of out of it. Same rules as bs-kit
 * and bs-kit-a: light from the left, edges in the deep steps, framed pieces small and looping, `rows`
 * the still for Reduce Motion, and each blurb says where its piece stands.
 *
 * NATIVE-OWNED, like everything in scenes/ (CONSTITUTION 5.5: new art never goes in the web-synced
 * sprite files).
 */
