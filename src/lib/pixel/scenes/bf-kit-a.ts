/**
 * Behavioral Finance art kit, batch A (lessons 2 to 9): what more than one of those lessons builds on.
 *
 * THE FAIRGROUND STAGE. The social and system lessons (herd, framing, nudges, the rules you write
 * yourself, and later stories, media, feeds and layered portfolios) happen OUTSIDE the head, so they
 * share one 80x60 set: the night fairground of the pathway backdrop seen up close. A striped big top on
 * the left, a Ferris wheel on the right, a string of bulbs overhead, a midway floor with confetti. The
 * middle is left open for a lesson's cast and props. Only the tent and the floor are in the base; the
 * wheel, its stand and the bulbs are layers, because thin diagonal lines in a base split the sky
 * around them into dozens of rects. Spread bfFairgroundLayers first, then the lesson's own layers.
 *
 * THE CAST, EXTENDED. bfHareHop is System 1 on the move (a two-frame hop, ears back); bfMirror turns
 * any sprite to face the other way, so the cast can enter from either side.
 *
 * House rules as bf-kit.ts: deep-step outlines, framed sprites within the 32x32 area (the bulb
 * string is 80x11, 880 pixels, the same allowance the kit's 40x17 tortoise uses), nothing web-synced.
 */
