/** The same sprite facing the other way, frames and all. */
export function bfMirror(sprite: PixelSprite, id: string): PixelSprite {
  const flip = (rows: string[]) => rows.map((row) => [...row].reverse().join(''));
  return { ...sprite, id, rows: flip(sprite.rows), ...(sprite.frames ? { frames: sprite.frames.map(flip) } : {}) };
}

