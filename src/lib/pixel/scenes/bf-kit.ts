/**
 * Behavioral Finance art kit: the pieces every lesson in this pathway builds its scenes from.
 *
 * THE CAST. System 1 is a hare (fast, jumpy, emotional) and System 2 is a tortoise (slow, calm,
 * carrying the written plan), after "Thinking, Fast and Slow" and the fable it echoes: the hare
 * loses the race the same way the average investor loses the DALBAR gap. Each has an idle loop and
 * one action pose so far; later lessons add poses here rather than redrawing the animals.
 *
 * THE STAGE. bfMindRoom is the inside of an investor's head: two hemispheres for a ceiling (orchid
 * over the calm side, hot pink over the impulsive side), two eye windows looking out on the market,
 * and a console along the back wall. It carries nothing lesson-specific, so a lesson paints what the
 * eyes see as its own layers and drops cast, shadows and props on top.
 *
 * THE KEEPSAKE EMBLEMS. Every lesson's keepsake is the same specimen jar (bf1-finish.ts) holding a
 * different emblem from this file: the bias the lesson caught. Emblems stay within 16x20 so they
 * float clear of the glass.
 *
 * House rules, as the pilot: outlines in the deep steps, framed sprites within 32x32 pixels, and
 * nothing here is web-synced (CONSTITUTION 5.5).
 */
import type { PixelSprite } from '../types';

/**
 * The same sprite starting elsewhere in its cycle and ticking at its own pace. Frames tick from
 * mount with no offset (PixelSpriteView), so two layers sharing one sprite would move in step; a
 * twinkle `phase` only offsets opacity, not the shape.
 */
export function bfLater(sprite: PixelSprite, id: string, by: number, frameMs: number): PixelSprite {
  const frames = sprite.frames ?? [sprite.rows];
  return { ...sprite, id, frames: [...frames.slice(by), ...frames.slice(0, by)], frameMs };
}

