/**
 * Business Strategy art kit, batch A (lessons 2 to 9): four more places to stand and the people who
 * stand in them, so the pathway's openers stop all being the war room.
 *
 * Sets (80x60 opener bases, like bsWarRoom): a night harbour, a council hall, a hillside over a
 * river, and a market square. The cast: the strategist on their feet (pointing, or reaching to shake
 * a hand), seated councillors and backers seen over a table, townsfolk, and coins. Same rules as
 * bs-kit: light from the left, edges in the deep steps, framed pieces small and looping, `rows` the
 * still for Reduce Motion, and each blurb says where its piece stands. bsMirrored and bsRecoloured
 * turn one figure into a crowd (facing the other way, in another house's colours) without new rows.
 *
 * NATIVE-OWNED, like everything in scenes/ (CONSTITUTION 5.5: new art never goes in the web-synced
 * sprite files).
 */
import type { PixelSprite } from '../types';
import { bsMoved } from './bs-kit';

/** A sprite facing the other way: every row of the still and of each frame read right to left. */
export function bsMirrored(sprite: PixelSprite, id: string): PixelSprite {
  const flip = (rows: string[]) => rows.map((row) => [...row].reverse().join(''));
  return { ...sprite, id, rows: flip(sprite.rows), ...(sprite.frames ? { frames: sprite.frames.map(flip) } : {}) };
}

/**
 * The same sprite in other colours: each character named in `swaps` becomes its value, in the still
 * and every frame. `palette` overrides the sprite's own tones (a different skin or hair, say).
 */
export function bsRecoloured(
  sprite: PixelSprite,
  id: string,
  swaps: Readonly<Record<string, string>>,
  palette?: Readonly<Record<string, string>>,
): PixelSprite {
  const tint = (rows: string[]) => rows.map((row) => row.replace(/./g, (ch) => swaps[ch] ?? ch));
  return {
    ...sprite,
    id,
    rows: tint(sprite.rows),
    ...(sprite.frames ? { frames: sprite.frames.map(tint) } : {}),
    ...(palette ? { palette: { ...sprite.palette, ...palette } } : {}),
  };
}

