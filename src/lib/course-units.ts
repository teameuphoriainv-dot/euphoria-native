/** How many lessons each named unit covers. */
export const LESSONS_PER_UNIT = 5;

/**
 * The unit name covering a zero-based lesson index, or null.
 *
 * Returns null rather than a placeholder for an unknown course or an index past the last named
 * unit: a course with more lessons than names should render the plain list it rendered before,
 * not "Unit 6" with nothing after it.
 */
export function unitNameFor(courseId: string, lessonIndex: number): string | null {
  const names = COURSE_UNITS[courseId];
  if (!names) return null;
  return names[Math.floor(lessonIndex / LESSONS_PER_UNIT)] ?? null;
}
