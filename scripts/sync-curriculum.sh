#!/bin/sh
# =============================================================================
# sync-curriculum.sh — LINKED curriculum sync:  WEB  ==>  NATIVE
# =============================================================================
#
#   THE WEB REPO IS THE PERMANENT SOURCE OF TRUTH.
#
#   Everything this script writes into src/lib/curriculum/ is GENERATED.
#   NEVER hand-edit a synced file. Any edit you make there is destroyed the
#   next time someone runs this script.
#
#   To change curriculum content: edit it in the WEB repo
#   (src/features/pathway/**), then re-run this script here to pull it over.
#
#   Usage:
#     ./scripts/sync-curriculum.sh                 # defaults to ~/euphoriaweb-current
#     ./scripts/sync-curriculum.sh /path/to/web    # explicit web repo root
#
#   The script is IDEMPOTENT — re-running it always produces the same tree.
#
#   What it does:
#     1. Validates the web repo exists and has every file we need.
#     2. Copies types.ts, helpers.ts, courseIndex.ts, courses/*.ts and the
#        explorables types module that types.ts depends on.
#     3. Rewrites import paths for native's flatter layout.
#     4. Strips the React dependency out of the explorables types so the
#        curriculum data layer stays 100% UI-free (importable from node).
#     5. Regenerates stepTypes.generated.ts by ACTUALLY EVALUATING all 12
#        courses and counting every step.type that occurs (data-derived, not
#        schema-derived).
#     6. Runs a smoke check (25 lessons, non-empty steps, known lesson title).
#
#   Files this script OWNS (deleted + rewritten every run):
#     src/lib/curriculum/types.ts
#     src/lib/curriculum/helpers.ts
#     src/lib/curriculum/courseIndex.ts
#     src/lib/curriculum/explorableTypes.ts
#     src/lib/curriculum/stepTypes.generated.ts
#     src/lib/curriculum/courses/*.ts
#
#   Files this script does NOT touch (hand-written, safe to edit):
#     src/lib/curriculum/index.ts   <-- the public entry point for UI code
#
# =============================================================================

set -eu

WEB_ROOT="${1:-$HOME/euphoriaweb-current}"
SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
NATIVE_ROOT=$(CDPATH= cd -- "$SCRIPT_DIR/.." && pwd)

SRC="$WEB_ROOT/src/features/pathway"
DEST="$NATIVE_ROOT/src/lib/curriculum"

fail() {
  echo ""
  echo "  SYNC FAILED"
  echo "  -----------"
  echo "  $1"
  echo ""
  exit 1
}

# --- 1. validate the source of truth ----------------------------------------

if [ ! -d "$WEB_ROOT" ]; then
  fail "Web repo not found at: $WEB_ROOT
  The web repo is the source of truth for curriculum content.
  Pass its path explicitly:   ./scripts/sync-curriculum.sh /path/to/euphoriaweb-current"
fi

if [ ! -d "$SRC" ]; then
  fail "Found the web repo at $WEB_ROOT but not the pathway feature at:
    $SRC
  Has the curriculum moved in web? Update this script's SRC path."
fi

for required in \
  "$SRC/types.ts" \
  "$SRC/helpers.ts" \
  "$SRC/courseIndex.ts" \
  "$SRC/components/explorables/types.ts"
do
  [ -f "$required" ] || fail "Missing required source file: $required"
done

[ -d "$SRC/courses" ] || fail "Missing course data directory: $SRC/courses"

course_count=$(ls -1 "$SRC/courses"/*.ts 2>/dev/null | wc -l | tr -d ' ')
[ "$course_count" -gt 0 ] || fail "No .ts course files found in $SRC/courses"

echo "curriculum sync"
echo "  source of truth : $SRC"
echo "  destination     : $DEST"
echo ""

# --- 2. wipe generated artifacts, then copy fresh (idempotent) ---------------

rm -rf "$DEST/courses"
rm -f "$DEST/types.ts" "$DEST/helpers.ts" "$DEST/courseIndex.ts" \
      "$DEST/explorableTypes.ts" "$DEST/stepTypes.generated.ts"
mkdir -p "$DEST/courses"

cp "$SRC/types.ts"                          "$DEST/types.ts"
cp "$SRC/helpers.ts"                        "$DEST/helpers.ts"
cp "$SRC/courseIndex.ts"                    "$DEST/courseIndex.ts"
cp "$SRC/components/explorables/types.ts"   "$DEST/explorableTypes.ts"
cp "$SRC"/courses/*.ts                      "$DEST/courses/"

# --- 3/4. rewrite imports, strip React, stamp headers -----------------------

DEST="$DEST" node <<'PATCH_EOF'
const fs = require('fs');
const path = require('path');
const DEST = process.env.DEST;

const BANNER = [
  '// ============================================================================',
  '// AUTO-SYNCED FROM THE WEB REPO — DO NOT EDIT THIS FILE.',
  '// Source of truth: euphoriaweb-current/src/features/pathway/',
  '// Re-sync with:    ./scripts/sync-curriculum.sh',
  '// ============================================================================',
  '',
].join('\n');

function patch(rel, fn) {
  const p = path.join(DEST, rel);
  let s = fs.readFileSync(p, 'utf8');
  s = fn(s, rel);
  fs.writeFileSync(p, BANNER + s);
}

// types.ts lives one directory up from where the explorables types used to be.
patch('types.ts', (s) => {
  const needle = "'./components/explorables/types'";
  if (!s.includes(needle)) {
    throw new Error(
      "types.ts no longer imports from './components/explorables/types'. " +
      'Upstream layout changed — update sync-curriculum.sh.'
    );
  }
  return s.split(needle).join("'./explorableTypes'");
});

// explorableTypes.ts: the curriculum data layer must have ZERO React/UI
// dependency so it can be imported from plain node (tests, tooling, this
// script's own verification pass). Strip the component-facing declarations —
// they describe widget props, which are the UI worker's concern, not data.
patch('explorableTypes.ts', (s) => {
  const before = s;
  s = s.replace(/^import type \{ ComponentType \} from 'react';\n/m, '');
  s = s.replace(
    /export interface ExplorableWidgetProps \{[\s\S]*?\n\}\n/m,
    ''
  );
  s = s.replace(
    /export type ExplorableWidgetComponent = ComponentType<ExplorableWidgetProps>;\n/m,
    ''
  );
  if (s === before) {
    throw new Error(
      'explorableTypes.ts: expected React declarations to strip but found none. ' +
      'Upstream shape changed — re-check sync-curriculum.sh.'
    );
  }
  if (/\bfrom 'react'|ComponentType/.test(s)) {
    throw new Error(
      'explorableTypes.ts still references React after stripping. ' +
      'Upstream added a new React dependency — update sync-curriculum.sh.'
    );
  }
  return s.replace(/\n{3,}/g, '\n\n');
});

// PATCH: AnimatedVisual 'stack' segments — make `value` optional.
//
// WHY: web's corporateFinance.ts lesson 4 ships two stack segments with no
// `value` key at all (only label/percent/color). The web schema declares
// `value: string` as required, so the real data contradicts the real schema.
// Native compiles under `strict`, so we relax the type to match what the data
// actually contains. This is the SAFE direction: the renderer must treat
// `segments[].value` as possibly-undefined, which is the truth at runtime.
//
// Remove this patch once web fixes the source data.
patch('types.ts', (s) => {
  const re = /(\| \{ type: 'stack';[^\n]*?segments: \{ label: string; )value: string;/;
  if (!re.test(s)) {
    throw new Error(
      "types.ts: could not find the AnimatedVisual 'stack' segments declaration to patch. " +
      'Upstream changed — re-check the value-optional patch in sync-curriculum.sh.'
    );
  }
  return s.replace(re, '$1value?: string;');
});

patch('helpers.ts', (s) => s);
patch('courseIndex.ts', (s) => s);

// PATCH: annotate each course's `lessons` array as PathwayLesson[].
//
// WHY: web writes `const lessons = [ ... ]` with no annotation. Most lessons
// are built by helper fns (already correctly typed) but corporateFinance.ts
// lessons 1-5 are RAW object literals. Without a contextual type their
// `type: 'hookOpener'` fields widen to `string`, and `export default lessons`
// then fails to satisfy `Promise<PathwayLesson[]>` in courseIndex.ts.
// Annotating restores the literal types AND makes the raw lesson objects
// genuinely type-checked against the schema instead of silently widened.
let annotated = 0;
for (const f of fs.readdirSync(path.join(DEST, 'courses'))) {
  if (!f.endsWith('.ts')) continue;
  patch(path.join('courses', f), (s, rel) => {
    const importRe = /^import type \{ AnimatedVisual \} from '\.\.\/helpers';$/m;
    const declRe = /^const lessons = \[$/m;
    if (!importRe.test(s) || !declRe.test(s)) {
      throw new Error(
        `${rel}: expected \`import type { AnimatedVisual } from '../helpers';\` and ` +
        '`const lessons = [` to annotate. Upstream changed — update sync-curriculum.sh.'
      );
    }
    annotated++;
    return s
      .replace(importRe, "$&\nimport type { PathwayLesson } from '../types';")
      .replace(declRe, 'const lessons: PathwayLesson[] = [');
  });
}
if (annotated === 0) throw new Error('No course files were annotated — nothing was copied?');
PATCH_EOF

# --- 5/6. evaluate the real data: generate STEP_TYPES + smoke check ----------

BUILD_DIR=$(mktemp -d)
trap 'rm -rf "$BUILD_DIR"' EXIT INT TERM

DEST="$DEST" NATIVE_ROOT="$NATIVE_ROOT" BUILD_DIR="$BUILD_DIR" node <<'GEN_EOF'
const fs = require('fs');
const path = require('path');

const DEST = process.env.DEST;
const BUILD_DIR = process.env.BUILD_DIR;
const NATIVE_ROOT = process.env.NATIVE_ROOT;

let ts;
try {
  ts = require(path.join(NATIVE_ROOT, 'node_modules', 'typescript'));
} catch (e) {
  console.error('\n  SYNC FAILED\n  -----------');
  console.error('  typescript is not installed. Run `npm install` first.\n');
  process.exit(1);
}

// Transpile (no type-checking — fast) the synced tree to CommonJS so we can
// require it and inspect the REAL data rather than guessing from the schema.
const opts = {
  module: ts.ModuleKind.CommonJS,
  target: ts.ScriptTarget.ES2020,
  esModuleInterop: true,
};

function transpileDir(relDir) {
  const abs = path.join(DEST, relDir);
  fs.mkdirSync(path.join(BUILD_DIR, relDir), { recursive: true });
  for (const f of fs.readdirSync(abs)) {
    if (!f.endsWith('.ts') || f === 'index.ts') continue;
    const src = fs.readFileSync(path.join(abs, f), 'utf8');
    const out = ts.transpileModule(src, { compilerOptions: opts }).outputText;
    fs.writeFileSync(
      path.join(BUILD_DIR, relDir, f.replace(/\.ts$/, '.js')),
      out
    );
  }
}
transpileDir('.');
transpileDir('courses');

const idx = require(path.join(BUILD_DIR, 'courseIndex.js'));

(async () => {
  const counts = Object.create(null);
  let lessonTotal = 0;
  let stepTotal = 0;
  const problems = [];

  for (const course of idx.COURSES) {
    const lessons = await idx.loadCourseLessons(course.id);
    if (!Array.isArray(lessons) || lessons.length === 0) {
      problems.push(`${course.id}: loaded 0 lessons`);
      continue;
    }
    if (lessons.length !== course.totalLessons) {
      problems.push(
        `${course.id}: courseIndex says ${course.totalLessons} lessons, data has ${lessons.length}`
      );
    }
    lessonTotal += lessons.length;
    for (const lesson of lessons) {
      if (!Array.isArray(lesson.steps) || lesson.steps.length === 0) {
        problems.push(`${course.id} lesson ${lesson.num}: empty steps`);
        continue;
      }
      for (const step of lesson.steps) {
        const t = step && step.type;
        if (typeof t !== 'string') {
          problems.push(`${course.id} lesson ${lesson.num}: step with no type`);
          continue;
        }
        counts[t] = (counts[t] || 0) + 1;
        stepTotal++;
      }
    }
  }

  // --- smoke check ---------------------------------------------------------
  const IF_ID = 'investing-fundamentals';
  const inv = await idx.loadCourseLessons(IF_ID);
  if (inv.length !== 25) problems.push(`${IF_ID}: expected 25 lessons, got ${inv.length}`);
  if (!inv[0] || inv[0].title !== 'Introduction to Investing') {
    problems.push(`${IF_ID}: lesson 1 title is "${inv[0] && inv[0].title}", expected "Introduction to Investing"`);
  }

  if (problems.length) {
    console.error('\n  SYNC FAILED — data verification\n  ----------------------------');
    for (const p of problems) console.error('  * ' + p);
    console.error('');
    process.exit(1);
  }

  const sorted = Object.keys(counts).sort((a, b) => counts[b] - counts[a] || a.localeCompare(b));

  const lines = [];
  lines.push('// ============================================================================');
  lines.push('// AUTO-GENERATED by scripts/sync-curriculum.sh — DO NOT EDIT THIS FILE.');
  lines.push('//');
  lines.push('// These are the step `type` values that ACTUALLY occur in the 12 synced');
  lines.push('// course files, produced by evaluating the real data and counting — not by');
  lines.push('// reading the schema. A type in types.ts that never appears in the data will');
  lines.push('// NOT be listed here.');
  lines.push('//');
  lines.push(`// ${sorted.length} distinct types across ${stepTotal} steps in ${lessonTotal} lessons.`);
  lines.push('// ============================================================================');
  lines.push('');
  lines.push('/** Every step type present in the curriculum, most frequent first. */');
  lines.push('export const STEP_TYPES = [');
  for (const t of sorted) lines.push(`  '${t}',`);
  lines.push('] as const;');
  lines.push('');
  lines.push('export type StepType = (typeof STEP_TYPES)[number];');
  lines.push('');
  lines.push('/** Occurrence count per step type across all 12 courses. */');
  lines.push('export const STEP_TYPE_COUNTS: Record<StepType, number> = {');
  for (const t of sorted) lines.push(`  '${t}': ${counts[t]},`);
  lines.push('};');
  lines.push('');
  lines.push('/** Totals for the whole synced curriculum. */');
  lines.push('export const CURRICULUM_STATS = {');
  lines.push(`  courses: ${idx.COURSES.length},`);
  lines.push(`  lessons: ${lessonTotal},`);
  lines.push(`  steps: ${stepTotal},`);
  lines.push(`  distinctStepTypes: ${sorted.length},`);
  lines.push('} as const;');
  lines.push('');

  fs.writeFileSync(path.join(DEST, 'stepTypes.generated.ts'), lines.join('\n'));

  console.log('  step types (data-derived, desc by occurrence):');
  for (const t of sorted) {
    console.log('    ' + String(counts[t]).padStart(6) + '  ' + t);
  }
  console.log('');
  console.log(`  smoke check   : OK  (${IF_ID} -> 25 lessons, lesson 1 "Introduction to Investing")`);
  console.log(`  totals        : ${idx.COURSES.length} courses / ${lessonTotal} lessons / ${stepTotal} steps / ${sorted.length} step types`);
})().catch((e) => {
  console.error('\n  SYNC FAILED while evaluating curriculum data:\n');
  console.error('  ' + (e && e.stack ? e.stack : e));
  console.error('');
  process.exit(1);
});
GEN_EOF

# --- report ------------------------------------------------------------------

echo ""
echo "  copied:"
for f in explorableTypes.ts types.ts helpers.ts courseIndex.ts; do
  printf '    %8s  %s\n' "$(wc -l < "$DEST/$f" | tr -d ' ')" "src/lib/curriculum/$f"
done
for f in "$DEST"/courses/*.ts; do
  printf '    %8s  %s\n' "$(wc -l < "$f" | tr -d ' ')" "src/lib/curriculum/courses/$(basename "$f")"
done
printf '    %8s  %s\n' "$(wc -l < "$DEST/stepTypes.generated.ts" | tr -d ' ')" "src/lib/curriculum/stepTypes.generated.ts  (generated)"

TOTAL=$(cat "$DEST/explorableTypes.ts" "$DEST/types.ts" "$DEST/helpers.ts" \
            "$DEST/courseIndex.ts" "$DEST/stepTypes.generated.ts" \
            "$DEST"/courses/*.ts | wc -l | tr -d ' ')
echo ""
echo "  TOTAL LINES SYNCED: $TOTAL"
echo "  done. entry point: src/lib/curriculum/index.ts"
echo ""
