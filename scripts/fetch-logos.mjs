#!/usr/bin/env node
/**
 * Build-time logo fetch. Writes assets/logos/<SYM>.png plus a static require map.
 *
 * WHY THIS EXISTS, measured rather than assumed. 2026-08-20, seven Mag-7 rows against the live
 * proxy: AAPL 200 (28,756B), NVDA 200 (11,296B), TSLA 404-then-200, and MSFT/AMZN/META/GOOG all
 * 429. Polygon's free tier allows 5 requests/minute and a cold trade screen mounts seven rows in
 * one tick, so the tail is rate-limited and correctly falls back to the lettered badge.
 *
 * A server-side cache does NOT fix that. Measured the same day: the route module is re-evaluated
 * per request, so a module-scoped Map is empty every time, and Workers isolates in production are
 * equally short-lived. The only thing that removes a cold-start network call is bytes that are
 * already on disk. Hence build time.
 *
 * Logos change about never, so this runs on demand, not in CI on every push.
 *
 * Usage:
 *   node scripts/fetch-logos.mjs              # every symbol in src/lib/stocks.ts
 *   node scripts/fetch-logos.mjs AAPL MSFT    # just these
 *   node scripts/fetch-logos.mjs --selftest   # no network; asserts the classifier
 *   node scripts/fetch-logos.mjs --via-proxy   # through a running dev server, no key needed
 *
 * --via-proxy is the preferred path: the running proxy already holds POLYGON_API_KEY and already
 * transcodes WebP to PNG, so this script never touches a credential and gets the same bytes the
 * app would. It still respects the upstream 5/min ceiling by pacing identically.
 */
import { Buffer } from 'node:buffer';
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const OUT = 'assets/logos';
const MANIFEST = join(OUT, 'manifest.json');
const BASE = 'https://api.polygon.io';
/*
 * PACING, AND THE MISTAKE IT ENCODES.
 *
 * Free tier is 5 requests/minute. The first version used one 13s gap for both modes, which is
 * right for --direct (each symbol makes its two upstream calls 13s apart, so ~4.6/min) but WRONG
 * for --via-proxy: there, ONE proxy request costs TWO Polygon calls internally, so a 13s gap runs
 * at ~9.2 calls/min against a 5/min ceiling. Measured: a 67-symbol pass wrote ZERO and every
 * single symbol came back rate-limited. Half-speed pacing looked fine on a 24-symbol batch, where
 * 12 of 24 succeeded, which is exactly how a pacing bug hides.
 *
 * So the gap is per-mode, and reflects what each mode actually costs upstream.
 */
const GAP_DIRECT_MS = 13_000;
const GAP_PROXY_MS = 26_000;

/**
 * THE CLASSIFIER, and the whole reason this script has a self-test.
 *
 * The proxy shipped a bug where `!img.ok` meant "this company has no logo", so ONE rate-limited
 * response marked a real company as art-less. TSLA was recorded as a coverage gap on exactly that
 * evidence and it was wrong. Transient and permanent must never collapse into each other.
 */
export function classify(status) {
  if (status === 200) return 'ok';
  if (status === 429 || status >= 500) return 'retry';   // transient: never recorded
  if (status === 404 || status === 410) return 'no_art'; // permanent: recorded, never re-fetched
  return 'retry';                                        // unknown: assume transient, be safe
}

function loadManifest() {
  try { return JSON.parse(readFileSync(MANIFEST, 'utf8')); } catch { return {}; }
}

function symbolsFromRepo() {
  const src = readFileSync('src/lib/stocks.ts', 'utf8');
  const block = src.slice(src.indexOf('export const STOCKS'));
  return [...new Set([...block.matchAll(/^\s{2}([A-Z][A-Z.]{0,5}):\s*\{/gm)].map((m) => m[1]))];
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function fetchViaProxy(sym, base) {
  const res = await fetch(`${base}/api/market?action=logo&sym=${encodeURIComponent(sym)}`);
  const verdict = classify(res.status);
  if (verdict !== 'ok') return { verdict };
  return { verdict: 'ok', buf: Buffer.from(await res.arrayBuffer()) };
}

async function fetchOne(sym, key) {
  const meta = await fetch(`${BASE}/v3/reference/tickers/${sym}?apiKey=${key}`);
  const verdict = classify(meta.status);
  if (verdict !== 'ok') return { verdict };
  const brand = (await meta.json())?.results?.branding ?? {};
  const src = brand.icon_url ?? brand.logo_url;
  if (!src) return { verdict: 'no_art' };
  await sleep(GAP_DIRECT_MS);
  const img = await fetch(`${src}${src.includes('?') ? '&' : '?'}apiKey=${key}`);
  const iv = classify(img.status);
  if (iv !== 'ok') return { verdict: iv };
  return { verdict: 'ok', buf: Buffer.from(await img.arrayBuffer()) };
}

function writeIndex() {
  /* Metro cannot require() a computed path, so the map has to be literal and generated. */
  const files = readdirSync(OUT).filter((f) => f.endsWith('.png')).sort();
  const body = files.map((f) => `  ${f.replace('.png', '')}: require('./${f}'),`).join('\n');
  writeFileSync(join(OUT, 'index.ts'),
`// GENERATED by scripts/fetch-logos.mjs. Do not edit.
// Metro requires literal paths, so a computed require() cannot work here.
export const BUNDLED_LOGOS: Record<string, number> = {
${body}
};
`);
  return files.length;
}

if (process.argv.includes('--selftest')) {
  const eq = (a, b, m) => { if (a !== b) throw new Error(`${m}: got ${a}, want ${b}`); };
  eq(classify(200), 'ok', '200 is a hit');
  eq(classify(429), 'retry', '429 must be transient, never recorded as no_art');
  eq(classify(503), 'retry', '5xx must be transient');
  eq(classify(404), 'no_art', '404 is genuinely no art');
  eq(classify(410), 'no_art', '410 is genuinely no art');
  eq(classify(418), 'retry', 'unknown statuses default to transient');
  const syms = symbolsFromRepo();
  if (syms.length < 5) throw new Error(`symbol scrape found only ${syms.length}: ${syms}`);
  if (!syms.includes('GOOGL')) throw new Error(`expected GOOGL in ${syms}`);
  console.log(`selftest ok — classifier 6/6, scraped ${syms.length} symbols: ${syms.join(' ')}`);
  process.exit(0);
}

const viaProxy = process.argv.includes('--via-proxy');
const proxyBase = process.env.PROXY_BASE ?? 'http://localhost:8081';
const key = process.env.POLYGON_API_KEY;
if (!viaProxy && !key) {
  console.error('POLYGON_API_KEY not set. Either export it, or start the dev server and pass --via-proxy.');
  process.exit(1);
}
mkdirSync(OUT, { recursive: true });
const manifest = loadManifest();
const args = process.argv.slice(2).filter((a) => !a.startsWith('--'));
const syms = args.length ? args : symbolsFromRepo();
let wrote = 0, skipped = 0, noArt = 0, failed = [];

for (const sym of syms) {
  const file = join(OUT, `${sym}.png`);
  // Resumable on purpose: a 5/min ceiling means this WILL be interrupted, and re-running must
  // not spend quota re-fetching what is already on disk.
  if (existsSync(file)) { skipped++; continue; }
  if (manifest[sym] === 'no_art') { noArt++; continue; }
  process.stdout.write(`  ${sym} ... `);
  try {
    const { verdict, buf } = viaProxy ? await fetchViaProxy(sym, proxyBase) : await fetchOne(sym, key);
    if (verdict === 'ok') {
      const sharp = (await import('sharp')).default;
      /*
       * RESIZE, BECAUSE THESE ARE BADGES AND THE SOURCE ART IS NOT.
       *
       * SIZED AND ENCODED FOR A BADGE, because that is all this ever is.
       *
       * MEASURED: every TickerLogo call site renders at 42-44pt (trade 44, search 42, movers 42),
       * so 132px covers @3x exactly and 144 leaves headroom. Polygon re-serves whatever the
       * company uploaded at whatever size they uploaded it -- NVDA arrived at 62,996 bytes.
       *
       * `palette: true` is the bigger win of the two. Logos are flat brand art with few colours,
       * so an indexed PNG encodes them far more cheaply than truecolour. Across 203 logos:
       * 3.48MB -> 0.78MB, 77% smaller. Checked visually against the hardest cases in the set
       * before adopting -- the JPMC copper gradient and Disney's fine linework are indistinguishable
       * from the 192px truecolour versions at render size.
       *
       * `fit: inside` preserves aspect ratio; `withoutEnlargement` leaves smaller art alone.
       */
      writeFileSync(file, await sharp(buf)
        .resize(144, 144, { fit: 'inside', withoutEnlargement: true })
        .png({ palette: true, quality: 90, compressionLevel: 9 })
        .toBuffer());
      manifest[sym] = 'ok'; wrote++; console.log('written');
    } else if (verdict === 'no_art') {
      manifest[sym] = 'no_art'; noArt++; console.log('no art (recorded, will not retry)');
    } else {
      failed.push(sym); console.log('rate-limited (NOT recorded, retry later)');
    }
  } catch (e) { failed.push(sym); console.log(`error: ${String(e).slice(0, 70)}`); }
  writeFileSync(MANIFEST, JSON.stringify(manifest, null, 2));
  await sleep(viaProxy ? GAP_PROXY_MS : GAP_DIRECT_MS);
}

const total = writeIndex();
console.log(`\nwrote ${wrote}, skipped ${skipped} already on disk, ${noArt} genuinely have no art`);
if (failed.length) console.log(`rate-limited, re-run to continue: ${failed.join(' ')}`);
console.log(`assets/logos/index.ts now maps ${total} logos`);
