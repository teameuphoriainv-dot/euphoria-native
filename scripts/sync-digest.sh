#!/bin/sh
# =============================================================================
# sync-digest.sh — LINKED Digest sync:  WEB  ==>  NATIVE
# =============================================================================
#
#   THE WEB REPO IS THE PERMANENT SOURCE OF TRUTH.
#
#   Everything this script writes is GENERATED. NEVER hand-edit a synced file.
#   Any edit you make there is destroyed the next time someone runs this script.
#
#   To change Digest content: edit it in the WEB repo
#   (src/features/digest/content/**), then re-run this script here to pull it over.
#
#   Usage:
#     ./scripts/sync-digest.sh                 # defaults to ~/euphoriaweb-current
#     ./scripts/sync-digest.sh /path/to/web    # explicit web repo root
#
#   The script is IDEMPOTENT — re-running it always produces the same tree.
#
#   What it does:
#     1. Validates the web repo exists and has the digest content it needs.
#     2. Reads every posts/*.ts and pulls slug/title/excerpt/category/date/
#        readMinutes/hero/body out of the real files.
#     3. Resolves hero keys through the web's own heroes.ts import map, then
#        INLINES each referenced .svg — native has no .svg transformer in
#        metro.config.js, so illustrations ship as SvgXml markup strings.
#     4. Regenerates the three native files below.
#     5. Verifies: every post has a body and a resolvable hero, every inline
#        ![alt](key) reference resolves, and the body markdown uses only the
#        block kinds components/digest-body.tsx can render.
#
#   Files this script OWNS (rewritten every run):
#     src/lib/digest-content.ts
#     src/lib/digest-bodies.ts
#     src/lib/digest-heroes.ts
#
#   Files this script does NOT touch (hand-written, safe to edit):
#     src/components/digest-body.tsx   <-- the markdown renderer
#     src/app/(tabs)/digest.tsx        <-- the Digest tab
#     src/app/digest/[slug].tsx        <-- the article reader
#
# =============================================================================

set -eu

WEB_ROOT="${1:-$HOME/euphoriaweb-current}"
SCRIPT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
NATIVE_ROOT=$(CDPATH= cd -- "$SCRIPT_DIR/.." && pwd)

SRC="$WEB_ROOT/src/features/digest"
DEST="$NATIVE_ROOT/src/lib"

fail() {
  echo ""
  echo "  SYNC FAILED"
  echo "  -----------"
  echo "  $1"
  echo ""
  exit 1
}

# --- 1. validate the source of truth ----------------------------------------

if [ ! -d "$WEB_ROOT" ]; then
  fail "Web repo not found at: $WEB_ROOT
  The web repo is the source of truth for Digest content.
  Pass its path explicitly:   ./scripts/sync-digest.sh /path/to/euphoriaweb-current"
fi

if [ ! -d "$SRC/content/posts" ]; then
  fail "Found the web repo at $WEB_ROOT but not the digest posts at:
    $SRC/content/posts
  Has Digest moved in web? Update this script's SRC path."
fi

[ -f "$SRC/content/heroes.ts" ] || fail "Missing hero registry: $SRC/content/heroes.ts"

post_count=$(ls -1 "$SRC/content/posts"/*.ts 2>/dev/null | wc -l | tr -d ' ')
[ "$post_count" -gt 0 ] || fail "No .ts post files found in $SRC/content/posts"

echo "digest sync"
echo "  source of truth : $SRC/content"
echo "  destination     : $DEST"
echo ""

# --- 2/3/4/5. parse posts, inline heroes, generate, verify ------------------

SRC="$SRC" DEST="$DEST" node <<'GEN_EOF'
const fs = require('fs');
const path = require('path');

const SRC = process.env.SRC;
const DEST = process.env.DEST;

const BANNER = (what, extra) =>
  [
    '// ============================================================================',
    '// AUTO-SYNCED FROM THE WEB REPO — DO NOT EDIT THIS FILE.',
    `// ${what}`,
    '// Source of truth: euphoriaweb-current/src/features/digest/content/',
    '// Re-sync with:    ./scripts/sync-digest.sh',
    ...(extra ? ['//', `// ${extra}`] : []),
    '// ============================================================================',
    '',
  ].join('\n');

const die = (msg) => {
  console.error('\n  SYNC FAILED\n  -----------\n  ' + msg + '\n');
  process.exit(1);
};

// --- read a double-quoted TS string field, honouring escapes ---------------
function field(src, key, file) {
  const m = src.match(new RegExp('^\\s*' + key + ':\\s*"((?:[^"\\\\]|\\\\.)*)"', 'm'));
  if (!m) return null;
  // the file contains a JS string literal; let JSON do the unescaping
  try {
    return JSON.parse('"' + m[1] + '"');
  } catch (e) {
    die(`${file}: could not decode the ${key} field.`);
  }
}
function numField(src, key) {
  const m = src.match(new RegExp('^\\s*' + key + ':\\s*(\\d+)', 'm'));
  return m ? Number(m[1]) : null;
}

// --- 3. hero key -> inlined svg, resolved through web's own heroes.ts -------
const heroesSrc = fs.readFileSync(path.join(SRC, 'content/heroes.ts'), 'utf8');

const imports = {};
for (const m of heroesSrc.matchAll(/^import\s+(\w+)\s+from\s+"([^"]+)";$/gm)) {
  imports[m[1]] = m[2];
}

const mapBody = heroesSrc.match(/HERO_IMAGES:\s*Record<string,\s*string>\s*=\s*\{([\s\S]*?)\n\};/);
if (!mapBody) die('heroes.ts: could not find the HERO_IMAGES map. Upstream shape changed.');

const heroes = {};
for (const line of mapBody[1].split('\n')) {
  const t = line.trim().replace(/,$/, '');
  if (!t) continue;
  let key, ident;
  const kv = t.match(/^"([^"]+)":\s*(\w+)$/);
  if (kv) { key = kv[1]; ident = kv[2]; }
  else if (/^\w+$/.test(t)) { key = t; ident = t; }   // shorthand { analytics, }
  else continue;

  const rel = imports[ident];
  if (!rel) die(`heroes.ts: "${key}" maps to ${ident}, which has no import.`);

  // web aliases @/ to src/
  const abs = rel.startsWith('@/')
    ? path.join(SRC, '../../', rel.slice(2))
    : path.resolve(path.join(SRC, 'content'), rel);

  if (!fs.existsSync(abs)) die(`hero "${key}" -> ${abs} does not exist.`);
  heroes[key] = fs
    .readFileSync(abs, 'utf8')
    .replace(/<\?xml[\s\S]*?\?>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

// --- 2. parse every post ----------------------------------------------------
const files = fs.readdirSync(path.join(SRC, 'content/posts')).filter((f) => f.endsWith('.ts'));
const posts = [];
for (const f of files) {
  const src = fs.readFileSync(path.join(SRC, 'content/posts', f), 'utf8');
  const p = {
    slug: field(src, 'slug', f),
    title: field(src, 'title', f),
    excerpt: field(src, 'excerpt', f),
    category: field(src, 'category', f),
    date: field(src, 'date', f),
    readMinutes: numField(src, 'readMinutes'),
    hero: field(src, 'hero', f),
    body: field(src, 'body', f),
  };
  for (const k of ['slug', 'title', 'excerpt', 'category', 'date', 'hero', 'body']) {
    if (!p[k]) die(`${f}: missing or unreadable "${k}".\n  Every post needs it for the app.`);
  }
  if (!p.readMinutes) die(`${f}: missing readMinutes.`);

  // Derive the read time from the prose instead of trusting the hand-authored field. Half the
  // library disagreed with its own body — one post claimed 7 minutes for 552 words. 225 wpm is a
  // standard adult reading pace; figures get a few seconds each.
  const words = p.body.split(/\s+/).filter(Boolean).length;
  const figures = [...p.body.matchAll(/!\[[^\]]*\]\([^)]+\)/g)].length;
  p.words = words;
  p.statedMinutes = p.readMinutes;
  p.readMinutes = Math.max(1, Math.round(words / 225 + figures * 0.1));

  posts.push(p);
}
posts.sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : a.slug.localeCompare(b.slug)));

// --- 5. verification --------------------------------------------------------
const problems = [];
const RENDERABLE = /^(## |### |> |- |!\[)/;

for (const p of posts) {
  if (!heroes[p.hero]) problems.push(`${p.slug}: hero "${p.hero}" is not in HERO_IMAGES`);
  // em dashes are banned in Digest copy; fail the sync rather than let one reach the app
  for (const [field, value] of [['title', p.title], ['excerpt', p.excerpt], ['body', p.body]]) {
    if (value.includes('—')) problems.push(`${p.slug}: em dash in ${field} — rewrite it in the web post`);
  }
  for (const m of p.body.matchAll(/!\[[^\]]*\]\(([^)]+)\)/g)) {
    if (!heroes[m[1]]) problems.push(`${p.slug}: inline image "${m[1]}" is not in HERO_IMAGES`);
  }
  for (const raw of p.body.split('\n')) {
    const line = raw.trim();
    if (!line) continue;
    // anything that is not a recognised block marker is rendered as a paragraph,
    // which is fine — but a stray "# " or "|table|" means the renderer will lie.
    if (/^#\s/.test(line)) problems.push(`${p.slug}: "# " h1 is not rendered by digest-body.tsx`);
    if (/^\s*\|.*\|\s*$/.test(line)) problems.push(`${p.slug}: markdown table is not rendered by digest-body.tsx`);
    if (/^\d+\.\s/.test(line)) problems.push(`${p.slug}: ordered list is not rendered by digest-body.tsx`);
    void RENDERABLE;
  }
}
if (problems.length) {
  console.error('\n  SYNC FAILED — content verification\n  ---------------------------------');
  for (const x of [...new Set(problems)]) console.error('  * ' + x);
  console.error('');
  process.exit(1);
}

// --- 4. generate ------------------------------------------------------------
const catOrder = [...new Set(posts.map((p) => p.category))];

const content = [
  BANNER('Digest post metadata (excerpts are app-voice, authored in web alongside the post).'),
  `export type DigestCategory = ${catOrder.map((c) => JSON.stringify(c)).join(' | ')};`,
  '',
  'export type DigestPost = {',
  '  slug: string;',
  '  title: string;',
  '  excerpt: string;',
  '  category: DigestCategory;',
  '  date: string;',
  '  readMinutes: number;',
  '  /** Key into DIGEST_HEROES. */',
  '  hero: string;',
  '};',
  '',
  '/** Newest first. */',
  'export const DIGEST_POSTS: DigestPost[] = [',
  ...posts.map(
    (p) =>
      `  { slug: ${JSON.stringify(p.slug)}, title: ${JSON.stringify(p.title)}, excerpt: ${JSON.stringify(
        p.excerpt,
      )}, category: ${JSON.stringify(p.category)}, date: ${JSON.stringify(p.date)}, readMinutes: ${
        p.readMinutes
      }, hero: ${JSON.stringify(p.hero)} },`,
  ),
  '];',
  '',
  'export const DIGEST_CATEGORIES = [...new Set(DIGEST_POSTS.map((p) => p.category))] as DigestCategory[];',
  '',
].join('\n');

const bodies = [
  BANNER(
    'Full article prose, copied verbatim from the web post files.',
    'Markdown subset: ## headings, paragraphs, - bullets, > quotes, ![alt](heroKey), **bold**.',
  ),
  'export const DIGEST_BODIES: Record<string, string> = {',
  ...posts.map((p) => `  ${JSON.stringify(p.slug)}: ${JSON.stringify(p.body)},`),
  '};',
  '',
  'export const bodyFor = (slug: string): string | undefined => DIGEST_BODIES[slug];',
  '',
].join('\n');

const heroesOut = [
  BANNER(
    'Hero + inline illustrations, inlined as SvgXml markup.',
    'Inlined rather than imported because metro.config.js has no .svg transformer.',
  ),
  'export const DIGEST_HEROES: Record<string, string> = {',
  ...Object.keys(heroes)
    .sort()
    .map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(heroes[k])},`),
  '};',
  '',
  'export const heroSvg = (key: string): string | undefined => DIGEST_HEROES[key];',
  '',
].join('\n');

fs.writeFileSync(path.join(DEST, 'digest-content.ts'), content);
fs.writeFileSync(path.join(DEST, 'digest-bodies.ts'), bodies);
fs.writeFileSync(path.join(DEST, 'digest-heroes.ts'), heroesOut);

const bodyChars = posts.reduce((n, p) => n + p.body.length, 0);
const used = new Set(posts.map((p) => p.hero));
for (const p of posts) for (const m of p.body.matchAll(/!\[[^\]]*\]\(([^)]+)\)/g)) used.add(m[1]);

const retimed = posts.filter((p) => p.readMinutes !== p.statedMinutes);
if (retimed.length) {
  console.log(`  read times   : recomputed from prose, ${retimed.length}/${posts.length} differed from the web field`);
  for (const p of retimed.sort((a, b) => Math.abs(b.statedMinutes - b.readMinutes) - Math.abs(a.statedMinutes - a.readMinutes)).slice(0, 5)) {
    console.log(`                 ${p.slug}: web said ${p.statedMinutes}, prose says ${p.readMinutes} (${p.words} words)`);
  }
}
console.log(`  posts        : ${posts.length}`);
console.log(`  categories   : ${catOrder.join(', ')}`);
console.log(`  body prose   : ${bodyChars.toLocaleString()} chars`);
console.log(`  heroes       : ${Object.keys(heroes).length} registered, ${used.size} referenced`);
const orphans = Object.keys(heroes).filter((k) => !used.has(k));
if (orphans.length) console.log(`  unreferenced : ${orphans.join(', ')}`);
GEN_EOF

# --- report ------------------------------------------------------------------

echo ""
echo "  wrote:"
for f in digest-content.ts digest-bodies.ts digest-heroes.ts; do
  printf '    %8s  %s\n' "$(wc -l < "$DEST/$f" | tr -d ' ')" "src/lib/$f"
done
echo ""
echo "  done. renderer: src/components/digest-body.tsx (hand-written, not synced)"
echo ""
